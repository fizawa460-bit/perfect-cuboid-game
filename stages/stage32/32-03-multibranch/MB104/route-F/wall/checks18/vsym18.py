#!/usr/bin/env python3
"""checks18 / vsym18.py -- V-symmetric slack-0 maps as Belyi maps (ANSWER-18, section 2.4).

A slack-0 map p of odd degree n with h o p = p o m_h for all h in the Klein group V (the half-turns about the three axes
of the octahedron) descends to a Belyi map pbar : P^1/V' -> P^1/V = P^1 of degree n, branched over the three images of
the pairs {0,oo}, {1,-1}, {i,-i}.  Its passport is (1 2^a_k 4^b_k), k = 1,2,3, with sum a_k = sum b_k = (n-1)/2.
This script enumerates the permutation triples (x, y, z), xyz = 1, transitive, with these cycle types, up to simultaneous
conjugacy, and reports for each passport the number of dessins and their monodromy groups (order, primitive or not).
Usage: python -I vsym18.py n [n ...]
"""
import sys, itertools, json
from collections import Counter, defaultdict


def cyc_type(p):
    n = len(p); seen = [False] * n; t = []
    for i in range(n):
        if not seen[i]:
            l = 0; j = i
            while not seen[j]: seen[j] = True; j = p[j]; l += 1
            t.append(l)
    return tuple(sorted(t, reverse=True))


def mul(p, q):  # first q then p
    return tuple(p[i] for i in q)


def inv(p):
    r = [0] * len(p)
    for i, x in enumerate(p): r[x] = i
    return tuple(r)


def perm_of_type(t):
    n = sum(t); p = list(range(n)); k = 0
    for l in t:
        for j in range(l): p[k + j] = k + (j + 1) % l
        k += l
    return tuple(p)


def class_elems(t):
    """all permutations of cycle type t (n <= 13: generated recursively)"""
    n = sum(t)
    out = []
    def rec(rem, parts, p):
        if not parts:
            q = list(p)
            out.append(tuple(q)); return
        l = parts[0]; first = min(rem)
        rest = rem - {first}
        same_next = len(parts) > 1 and parts[1] == l
        for tail in itertools.permutations(sorted(rest), l - 1):
            cyc = (first,) + tail
            for a, b in zip(cyc, cyc[1:] + cyc[:1]): p[a] = b
            rec(rem - set(cyc), parts[1:], p)
        # (cycles of equal length are ordered by their smallest element because 'first' is always min(rem))
    # order parts so that equal lengths are adjacent; choose cycle containing min(rem) for *some* part: need all
    # assignments of which length contains the minimum -> iterate over distinct lengths
    def rec2(rem, parts, p):
        if not parts:
            out.append(tuple(p)); return
        first = min(rem)
        for l in sorted(set(parts)):
            np_ = list(parts); np_.remove(l)
            rest = rem - {first}
            for tail in itertools.permutations(sorted(rest), l - 1):
                cyc = (first,) + tail
                for a, b in zip(cyc, cyc[1:] + cyc[:1]): p[a] = b
                rec2(rem - set(cyc), np_, p)
    rec2(frozenset(range(n)), list(t), list(range(n)))
    return out


def group_closure(gens, cap=200000):
    n = len(gens[0]); e = tuple(range(n)); S = {e}; frontier = [e]
    while frontier:
        nf = []
        for g in frontier:
            for h in gens:
                k = mul(h, g)
                if k not in S:
                    S.add(k); nf.append(k)
                    if len(S) > cap: return None
        frontier = nf
    return S


def transitive(gens):
    n = len(gens[0]); seen = {0}; st = [0]
    while st:
        i = st.pop()
        for g in gens:
            if g[i] not in seen: seen.add(g[i]); st.append(g[i])
    return len(seen) == n


def blocks(gens):
    """True if the transitive group generated by gens is imprimitive"""
    n = len(gens[0])
    for j in range(1, n):
        par = list(range(n))
        def f(a):
            while par[a] != a: par[a] = par[par[a]]; a = par[a]
            return a
        par[f(j)] = f(0); ch = True
        while ch:
            ch = False
            for g in gens:
                for a in range(n):
                    ra, rb = f(a), f(par[a])
                    x, y = f(g[a]), f(g[ra])
                    if x != y: par[x] = y; ch = True
        if len({f(a) for a in range(n)}) > 1: return True
    return False


def canon(x, y):
    """canonical form of the pair (x, y) under simultaneous conjugation, for a transitive pair: relabel by BFS from each start"""
    n = len(x); best = None
    for s in range(n):
        lab = {s: 0}; order = [s]; k = 0
        while k < len(order):
            a = order[k]; k += 1
            for g in (x, y):
                b = g[a]
                if b not in lab: lab[b] = len(order); order.append(b)
        cx = tuple(lab[x[order[i]]] for i in range(n)); cy = tuple(lab[y[order[i]]] for i in range(n))
        if best is None or (cx, cy) < best: best = (cx, cy)
    return best


def passports(n):
    opts = [(a, b) for b in range(n // 4 + 1) for a in [(n - 1 - 4 * b) // 2] if 1 + 2 * a + 4 * b == n and a >= 0]
    out = set()
    for c in itertools.product(opts, repeat=3):
        if sum(a for a, b in c) == (n - 1) // 2 and sum(b for a, b in c) == (n - 1) // 2: out.add(c)
    return sorted(out)


def typ(a, b): return tuple([4] * b + [2] * a + [1])


def main():
    for n in map(int, sys.argv[1:]):
        print(f"== n = {n}")
        for pp in passports(n):
            t1, t2, t3 = (typ(*c) for c in pp)
            x = perm_of_type(t1)
            found = {}
            for y in class_elems(t2):
                z = inv(mul(x, y))
                if cyc_type(z) != t3: continue
                if not transitive((x, y)): continue
                c = canon(x, y)
                if c not in found: found[c] = (x, y)
            stats = Counter()
            for c, (xx, yy) in found.items():
                G = group_closure([xx, yy], cap=50000)
                stats[(len(G) if G else ">50000", "imprimitive" if blocks((xx, yy)) else "primitive")] += 1
            print(json.dumps({"n": n, "passport(a,b)": pp, "dessins": len(found), "groups": {str(k): v for k, v in sorted(stats.items(), key=str)}}), flush=True)


if __name__ == "__main__":
    main()
