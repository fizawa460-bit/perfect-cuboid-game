# Bolza order Q_B = O_K<1,a,b,c=ab>, K=Q(sqrt2).  Work in Q_B/2Q_B (order 256).
# element: 4 coords, each (x,y) = x + y*s, s=sqrt2, mod 2 (s^2 = 0 mod 2).
import itertools, sys
def kadd(u,v): return ((u[0]+v[0])%2,(u[1]+v[1])%2)
def kmul(u,v): return ((u[0]*v[0]+2*u[1]*v[1])%2,(u[0]*v[1]+u[1]*v[0])%2)
Z=(0,0); O=(1,0); S=(0,1); M1=(1,0)  # -1 = 1 mod 2
def vec(c0=Z,c1=Z,c2=Z,c3=Z): return (c0,c1,c2,c3)
# multiplication table of basis (1,a,b,c): entries are vectors (exact signs irrelevant mod 2)
T={}
one=vec(O); a=vec(Z,O); b=vec(Z,Z,O); c=vec(Z,Z,Z,O)
T[(0,0)]=one; T[(0,1)]=a; T[(0,2)]=b; T[(0,3)]=c
T[(1,0)]=a; T[(2,0)]=b; T[(3,0)]=c
T[(1,1)]=vec(O,O)               # a^2 = a-1
T[(1,2)]=c                      # ab = c
T[(1,3)]=vec(Z,Z,O,O)           # ac = c-b
T[(2,1)]=vec((1,1),O,O,O)       # ba = (-1-s)+a+b-c
T[(2,2)]=vec(O,Z,O)             # b^2=b-1
T[(2,3)]=vec(O,O,S,Z)           # bc = -1+a-s b
T[(3,1)]=vec(O,S,O,Z)           # ca = -1 - s a + b
T[(3,2)]=vec(Z,O,Z,O)           # cb = c-a
T[(3,3)]=vec(O,Z,Z,S)           # c^2 = -1 - s c
def add(u,v): return tuple(kadd(x,y) for x,y in zip(u,v))
def mul(u,v):
    r=[Z]*4
    for i in range(4):
        if u[i]==Z: continue
        for j in range(4):
            if v[j]==Z: continue
            k=kmul(u[i],v[j]); t=T[(i,j)]
            for m in range(4):
                if t[m]!=Z: r[m]=kadd(r[m],kmul(k,t[m]))
    return tuple(r)
ks=[(0,0),(1,0),(0,1),(1,1)]
ALL=[tuple(v) for v in itertools.product(ks,repeat=4)]
# associativity on basis
B=[one,a,b,c]
assert all(mul(mul(x,y),z)==mul(x,mul(y,z)) for x in B for y in B for z in B)
zero=vec()
# units and radical
units=[x for x in ALL if any(mul(x,y)==one for y in ALL)]
J=[x for x in ALL if x not in set(units)]
Js=set(J)
assert all(add(x,y) in Js for x in J for y in J)
print("ring",len(ALL),"units",len(units),"radical",len(J))
def span_prod(A,Bs):
    P={zero}
    gens={mul(x,y) for x in A for y in Bs}
    ch=True
    while ch:
        ch=False
        for g in list(gens):
            for p in list(P):
                q=add(p,g)
                if q not in P: P.add(q); ch=True
    return P
J2=span_prod(J,J); J3=span_prod(J2,J); J4=span_prod(J3,J)
print("J^2",len(J2),"J^3",len(J3),"J^4",len(J4))
# group generated by alpha, beta
G={one}; fr=[one]
while fr:
    n=[]
    for x in fr:
        for g in (a,b):
            y=mul(x,g)
            if y not in G: G.add(y); n.append(y)
    fr=n
print("image of <alpha,beta> mod 2:",len(G))
def lvl(x):
    d=add(x,one)
    if d==zero: return 4
    if d in J3: return 3
    if d in J2: return 2
    if d in Js: return 1
    return 0
from collections import Counter
print("levels:",sorted(Counter(lvl(x) for x in G).items()))
L2=[x for x in G if lvl(x)>=2]; L3=[x for x in G if lvl(x)>=3]
print("|level>=2|",len(L2),"|level>=3|",len(L3))
print("level>=2 elementary abelian:",all(mul(x,x)==one for x in L2) and all(mul(x,y)==mul(y,x) for x in L2 for y in L2))
# all normal elementary abelian subgroups of order 8 in G
Gl=list(G)
inv={x:[y for y in Gl if mul(x,y)==one][0] for x in Gl}
invols=[x for x in Gl if x!=one and mul(x,x)==one]
print("involutions in the 96-group:",len(invols))
subs=set()
for x,y,z in itertools.combinations(invols,3):
    if mul(x,y)!=mul(y,x) or mul(x,z)!=mul(z,x) or mul(y,z)!=mul(z,y): continue
    H={one,x,y,z,mul(x,y),mul(x,z),mul(y,z),mul(mul(x,y),z)}
    if len(H)==8: subs.add(frozenset(H))
norm=[H for H in subs if all(mul(mul(g,h),inv[g]) in H for g in Gl for h in H)]
print("elementary abelian subgroups of order 8:",len(subs)," normal:",len(norm))
print("normal one equals level>=2 subgroup:",[H==frozenset(L2) for H in norm])
# normal subgroups of order 4 inside L2
n4=[]
for x,y in itertools.combinations([h for h in L2 if h!=one],2):
    H={one,x,y,mul(x,y)}
    if all(mul(mul(g,h),inv[g]) in H for g in Gl for h in H): n4.append(frozenset(H))
n4=set(n4); print("normal order-4 subgroups of L2:",len(n4),[H==frozenset(L3) for H in n4])
# conjugation action of the 96-group on L2: orbits
orb=Counter()
seen=set()
for h in L2:
    if h in seen: continue
    o={mul(mul(g,h),inv[g]) for g in Gl}; seen|=o
    print(" orbit size",len(o),"level",lvl(h))
