"""E13 Lemma 1 checks: the level quotient Gamma_0 / PQ^1(P^3) has order 2; products of two elliptic involutions
(found by traces.py) have level >= 3; the multiplication table of Q_B equals E01's bolza_mod2.py.
Run from the repository root:  python3 -I stages/stage32/32-03-multibranch/MB104/route-E/e13/check_lemma1.py"""
import sys, os, io, math, itertools, contextlib, importlib.util
from collections import Counter
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
def load(name, argv):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + ".py"))
    m = importlib.util.module_from_spec(spec); sys.argv = [name + ".py"] + argv
    with contextlib.redirect_stdout(io.StringIO()): spec.loader.exec_module(m)
    return m
F = load("filt", []); T = load("traces", ["9"])
L2, L3 = set(F.L2), set(F.L3)
ok = True
q = len(L2) // len(L3); print("level>=2 image", len(L2), "level>=3 image", len(L3), "quotient order", q); ok &= (q == 2)
ex2 = [x for x in L2 if x not in L3]
p23 = all(F.mul(x, y) in L3 for x in ex2 for y in ex2); print("level-2 times level-2 lies in level>=3:", p23); ok &= p23
lv = Counter(F.lvl(T.mod2(x)) for x in T.invs); print("elliptic involutions:", len(T.invs), "levels", dict(lv)); ok &= (set(lv) == {2})
pl = Counter(F.lvl(T.mod2(T.mul(x, y))) for x, y in itertools.combinations(T.invs, 2))
print("levels of products of two distinct elliptic involutions:", dict(pl)); ok &= (min(pl) >= 3)
src = open(os.path.join(HERE, "..", "bolza_mod2.py")).read(); g = {}
exec(src[:src.index("# sanity: associativity")], g)
basis = [T.one, T.a, T.b, T.V(T.Z, T.Z, T.Z, T.O)]
E = [[(1, 0) if k == i else (0, 0) for k in range(4)] for i in range(4)]
tab = all(list(g["qmul"](E[i], E[j])) == [c.key() for c in T.mul(basis[i], basis[j])] for i in range(4) for j in range(4))
print("multiplication table equals E01 bolza_mod2.py on 16 basis products:", tab); ok &= tab
U = F.units
inv = {u: [v for v in U if F.mul(u, v) == F.one][0] for u in U}
orbs = {frozenset(F.mul(F.mul(u, x), inv[u]) for u in U) for x in ex2}
sing = frozenset(T.mod2(x) for x in T.invs)
print("conjugation orbits of the level-2 classes:", sorted(len(o) for o in orbs), " size-3 orbit = singular classes:", sing in orbs)
ok &= (sorted(len(o) for o in orbs) == [1, 3] and sing in orbs)
gen = {F.one}
for x in sing:
    gen |= {F.mul(y, x) for y in gen}
print("subgroup generated by the three singular classes:", len(gen), "elements (= level>=2 image:", gen == L2, ")")
ok &= (gen == L2)
lmin = math.acosh(1 + math.sqrt(2)); ls = 3.045; R = math.acosh(math.cosh(ls) + math.sinh(ls) ** 2)
print("R(3.045) = %.4f, N = %.2f" % (R, (math.cosh(R + lmin / 2) - 1) / (math.cosh(lmin / 2) - 1)))
if not ok: raise SystemExit("FAIL")
print("PASS")
