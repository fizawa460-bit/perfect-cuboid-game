"""Route E check 1: image of Q1B = <alpha, beta> in (Q_B / 2 Q_B)^x.
Bolza order (Katz-Katz-Schein-Vishne, arXiv:1405.5454, Thm 7.1): Q_B = O_K<1,a,b,ab>, O_K = Z[sqrt2],
a^2 = a - 1, b^2 = b - 1, ba = (-1 - sqrt2) + a + b - ab.
Elements of O_K: pairs (x, y) = x + y*sqrt2.  Elements of Q_B: 4-tuples over O_K in the basis 1, a, b, ab."""
import itertools
def kadd(p, q): return (p[0] + q[0], p[1] + q[1])
def kmul(p, q): return (p[0]*q[0] + 2*p[1]*q[1], p[0]*q[1] + p[1]*q[0])
Z = (0, 0); ONE = (1, 0); M1 = (-1, 0); S = (0, 1)
# Left multiplication by a and b on the basis {1, a, b, ab} (Q_B is generated by a, b over O_K).
# a * e: a*1=a, a*a=-1+a, a*b=ab, a*(ab)=(a^2)b=(-1+a)b=-b+ab
La = {0:[Z,ONE,Z,Z], 1:[M1,ONE,Z,Z], 2:[Z,Z,Z,ONE], 3:[Z,Z,M1,ONE]}
# b * e: b*1=b, b*a=ba, b*b=-1+b, b*(ab)=(ba)b = ((-1-s2)+a+b-ab) b = (-1-s2)b + ab + b^2 - a b^2
#   b^2=-1+b, a b^2 = a(-1+b) = -a + ab  ->  (-1-s2)b + ab + (-1+b) - (-a+ab) = -1 + a + (-s2) b
Lb = {0:[Z,Z,ONE,Z], 1:[(-1,-1),ONE,ONE,M1], 2:[M1,Z,ONE,Z], 3:[M1,ONE,(0,-1),Z]}
# Left-regular representation: x = c0 + c1 a + c2 b + c3 ab acts as c0 I + c1 A + c2 B + c3 AB.
def mat(L): return [[L[i][k] for i in range(4)] for k in range(4)]  # column i = image of e_i
def mm(A, B): return [[ (lambda r,c: __import__('functools').reduce(kadd,[kmul(A[r][t],B[t][c]) for t in range(4)],Z))(r,c) for c in range(4)] for r in range(4)]
I4 = [[ONE if r==c else Z for c in range(4)] for r in range(4)]
A = mat(La); B = mat(Lb); AB = mm(A, B)
def leftmat(x):
    out = [[Z]*4 for _ in range(4)]
    for c, Mx in ((x[0], I4), (x[1], A), (x[2], B), (x[3], AB)):
        for r in range(4):
            for s in range(4): out[r][s] = kadd(out[r][s], kmul(c, Mx[r][s]))
    return out
def apply(Mx, y): return [__import__('functools').reduce(kadd,[kmul(Mx[r][t], y[t]) for t in range(4)],Z) for r in range(4)]
def qmul(x, y): return apply(leftmat(x), y)
# sanity: associativity on basis and relations
E = [[ONE if k==i else Z for k in range(4)] for i in range(4)]
if qmul(E[2], E[1]) != [(-1,-1),ONE,ONE,M1]: raise SystemExit("FAIL: relation ba")
for x, y, z in itertools.product(E, repeat=3):
    if qmul(qmul(x,y),z) != qmul(x,qmul(y,z)): raise SystemExit("FAIL: not associative")
# reduce mod 2: O_K/2 = {x + y s2 : x,y in Z/2}
def red(x): return tuple((c[0] % 2, c[1] % 2) for c in x)
ONEq = red(E[0]); a = red(E[1]); b = red(E[2])
def qm2(x, y): return red(qmul([tuple(c) for c in x], [tuple(c) for c in y]))
G = {ONEq}; frontier = [ONEq]
while frontier:
    nxt = []
    for g in frontier:
        for h in (a, b):
            p = qm2(g, h)
            if p not in G: G.add(p); nxt.append(p)
    frontier = nxt
def order(x):
    p, n = x, 1
    while p != ONEq: p = qm2(p, x); n += 1
    return n
ab = qm2(a, b)
print("image of <alpha,beta> in (Q_B/2Q_B)^x: order", len(G))
print("orders of images: alpha", order(a), " beta", order(b), " alpha*beta", order(ab))
from fractions import Fraction as Fr
chi = len(G) * (Fr(1,3) + Fr(1,3) + Fr(1,4) - 1)   # orbifold Euler characteristic of the (3,3,4) cover
print("Euler characteristic", chi, "-> genus", 1 - chi/2, "(area", -2*chi, "pi)")
if not (len(G) == 96 and (order(a), order(b), order(ab)) == (3, 3, 4) and 1 - chi/2 == 5):
    raise SystemExit("FAIL")
print("PASS")

# Independent check of the structure constants against explicit quaternions in D_B = (-3, sqrt2) over Q(sqrt2)
# KKSV (6.1), (6.2), Section 7: alpha = (1 + i)/2, gamma = (1/6)(3 + i)(1 - (1 + sqrt2) j),
# beta = alpha (1 - (1 - sqrt2) gamma).  (This agrees with the closed form (7.1); the product formula is used here.)
from fractions import Fraction as Q
def fa(p, q): return (p[0] + q[0], p[1] + q[1])
def fm(p, q): return (p[0]*q[0] + 2*p[1]*q[1], p[0]*q[1] + p[1]*q[0])
def fs(c, p): return (c*p[0], c*p[1])
F0 = (Q(0), Q(0))
SQ2 = (Q(0), Q(1))
AQ = (Q(-3), Q(0)); BQ = SQ2            # D_B = (-3, sqrt2): i^2 = -3, j^2 = sqrt2 (KKSV (1.2); disc of the standard order 4ab = 12 sqrt2)
def hmul(x, y):
    # basis 1, i, j, k = ij;  i^2 = a, j^2 = b, k^2 = -ab, ij = k, ji = -k, ik = a j, ki = -a j, jk = -b i, kj = b i
    a0, a1, a2, a3 = x; b0, b1, b2, b3 = y
    m = fm; A = AQ; B = BQ; AB = fm(AQ, BQ); mAB = fs(-1, AB)
    r0 = fa(fa(m(a0,b0), m(A, m(a1,b1))), fa(m(B, m(a2,b2)), m(mAB, m(a3,b3))))
    r1 = fa(fa(m(a0,b1), m(a1,b0)), fa(m(fs(-1,B), m(a2,b3)), m(B, m(a3,b2))))
    r2 = fa(fa(m(a0,b2), m(a2,b0)), fa(m(A, m(a1,b3)), m(fs(-1,A), m(a3,b1))))
    r3 = fa(fa(m(a0,b3), m(a3,b0)), fa(m(a1,b2), fs(-1, m(a2,b1))))
    return (r0, r1, r2, r3)
def hadd(*xs):
    out = (F0, F0, F0, F0)
    for x in xs: out = tuple(fa(out[k], x[k]) for k in range(4))
    return out
def hsc(c, x): return tuple(fm(c, x[k]) for k in range(4))
def nrd(x):
    a0, a1, a2, a3 = x  # nrd = a0^2 - a a1^2 - b a2^2 + ab a3^2
    return fa(fa(fm(a0,a0), fm(fs(-1,AQ), fm(a1,a1))), fa(fm(fs(-1,BQ), fm(a2,a2)), fm(fm(AQ,BQ), fm(a3,a3))))
one = ((Q(1),Q(0)), F0, F0, F0)
al = ((Q(1,2),Q(0)), (Q(1,2),Q(0)), F0, F0)
i_ = (F0, (Q(1),Q(0)), F0, F0); j_ = (F0, F0, (Q(1),Q(0)), F0)
ga = hmul(hsc((Q(1,6),Q(0)), hadd(hsc((Q(3),Q(0)), one), i_)), hadd(one, hsc((Q(-1),Q(-1)), j_)))
be = hmul(al, hadd(one, hsc((Q(-1),Q(1)), ga)))
checks0 = {"gamma^2 = (1+sqrt2) + gamma": hmul(ga, ga) == hadd(hsc((Q(1),Q(1)), one), ga),
           "gamma*alpha = -1 + alpha + gamma - alpha*gamma":
               hmul(ga, al) == hadd(hsc((Q(-1),Q(0)), one), al, ga, hsc((Q(-1),Q(0)), hmul(al, ga)))}
ab_ = hmul(al, be)
checks = dict(checks0)
checks.update({
    "nrd alpha = 1": nrd(al) == (Q(1),Q(0)),
    "nrd beta = 1": nrd(be) == (Q(1),Q(0)),
    "alpha^2 = alpha - 1": hmul(al, al) == hadd(al, hsc((Q(-1),Q(0)), one)),
    "beta^2 = beta - 1": hmul(be, be) == hadd(be, hsc((Q(-1),Q(0)), one)),
    "nrd gamma = -(1+sqrt2)": nrd(ga) == (Q(-1),Q(-1)),
    "beta*alpha = (-1-sqrt2) + alpha + beta - alpha*beta":
        hmul(be, al) == hadd(hsc((Q(-1),Q(-1)), one), al, be, hsc((Q(-1),Q(0)), ab_)),
    "alpha^3 = -1": hmul(al, hmul(al, al)) == hsc((Q(-1),Q(0)), one),
    "beta^3 = -1": hmul(be, hmul(be, be)) == hsc((Q(-1),Q(0)), one),
    "(alpha beta)^4 = -1": hmul(hmul(ab_, ab_), hmul(ab_, ab_)) == hsc((Q(-1),Q(0)), one),
})
for k, v in checks.items(): print(("ok   " if v else "FAIL ") + k)
if not all(checks.values()): raise SystemExit("FAIL: structure constants")
print("PASS: structure constants match explicit quaternions")
