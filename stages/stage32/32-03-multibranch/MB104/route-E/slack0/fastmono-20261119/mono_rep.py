"""Monodromy solver that tracks only one cover per symmetry orbit (variant of speedup-20261118/mono.py).

mono.py tracks *every* known cover around each random loop and then adds the images of new covers under
Stab(prof) in Aut(B) x <complex conjugation>.  But tracking s(X) around a loop g gives the same orbit as
tracking X around s^-1 g s, which is just another random loop.  So it is enough to track one representative
per orbit: the orbits reached are the same, and the work per loop drops by the orbit size (up to 48 for
2,2,2,2,2,2).  Everything else (exact dedupe by canonical monodromy tuple, analyse, to_u) is mono.py's code.

Extra: --groups asks for seeds until each requested monodromy group order is represented (2,2,2,2,2,2 in degree
7 splits into three braid orbits with groups S7, A7, PSL(3,2): orders 5040, 2520, 168), and a checkpoint is
written after every loop so a restart continues where it stopped.

usage: python3 mono_rep.py n t1,..,t6 [--loops N] [--seed S] [--scale X] [--groups 5040,2520,168]
                                       [--ckpt file] [--maxtime sec]"""
import sys, os, time, pickle, argparse
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, '../speedup-20261118'))
import mono
from mono import System, track, homB, analyse, analyse_loose
import closure, monodromy as md
import fasttuples as ft
import seed as _seed
from fractions import Fraction
from math import factorial
from hurwitz_char import C

def group_order(t):
    """order of the permutation group generated by the tuple (BFS closure, fine for n <= 8)"""
    n = len(t[0]); idt = tuple(range(n)); seen = {idt}; fr = [idt]
    gens = [tuple(g) for g in t]
    while fr:
        nf = []
        for h in fr:
            for g in gens:
                k = tuple(g[h[x]] for x in range(n))
                if k not in seen: seen.add(k); nf.append(k)
        fr = nf
    return len(seen)

TM = 12   # loop sampling for fasttuples (60 = monodromy.py's original)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('n', type=int); ap.add_argument('prof')
    ap.add_argument('--loops', type=int, default=200); ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--scale', type=float, default=2.0); ap.add_argument('--groups', default='')
    ap.add_argument('--ckpt', default=''); ap.add_argument('--maxtime', type=float, default=1e18)
    ap.add_argument('--all', action='store_true', help='track all covers (= mono.py behaviour, for comparison)')
    a = ap.parse_args()
    n = a.n; prof = tuple(int(x) for x in a.prof.split(',')); rng = np.random.default_rng(a.seed)
    tag = f'{n}_{"".join(map(str, prof))}'
    ckpt = a.ckpt or f'ckpt_rep_{tag}.pkl'
    target = float(Fraction(C(n, prof), factorial(n)))
    fixed = np.array([0.31 + 0.17j, -0.52 + 0.44j, 0.13 - 0.61j])
    import covers; covers.rng = rng
    L = rng.normal(size=2 * (n + 1)) + 1j * rng.normal(size=2 * (n + 1))
    S = System(n, prof, fixed, L); B0 = homB(); t0 = time.time()
    sols = []; orbit = []; reps = []; TUP = set(); REJ = []; W = 0.0; GRP = {}
    def an_of(u):
        p, q, cc = S.unpack(u[None])
        return analyse(p[0], q[0], n, prof, cc[0], list(S.ys)) or analyse_loose(p[0], q[0], n, prof, cc[0], list(S.ys))
    def accept(Us, oid=None):
        """add new covers; oid=None -> each new cover opens its own orbit (its images join it)"""
        nonlocal W
        Us = [u for u in Us if an_of(u) is not None or REJ.append(u.copy())]
        if not Us: return []
        Us = np.array(Us); p, q, _ = S.unpack(Us); new = []
        for u, t in zip(Us, ft.tuples(p, q, TM)):
            if not md.check(t, prof): REJ.append(u.copy()); continue
            cf, au = md.canon(t)
            if cf is None or cf in TUP: continue
            TUP.add(cf); W += 1 / au; sols.append(u)
            if oid is None:
                o = len(reps); reps.append(len(sols) - 1); g = group_order(t); GRP[o] = g
            else: o = oid
            orbit.append(o); new.append((u, o))
        return new
    # mono.py's to_u, reused through a tiny shim (it is a closure inside mono.main, so copy its body)
    def to_u(x2, an2):
        crit = [z for y in range(6) for z in an2[y][1]]; ysl = [y for y in range(6) for z in an2[y][1]]
        if any(z is None for z in crit): return None
        crit = np.array(crit, complex); ysl = np.array(ysl); idx = []; used = set()
        for y in S.ys:
            cand = [k for k in range(len(crit)) if ysl[k] == y and k not in used]; used.add(cand[0]); idx.append(cand[0])
        cs = crit[idx]
        def frame(pp):
            Mt = np.array([[pp[0], pp[1]], [1, 1]], complex); lm = np.linalg.solve(Mt, np.array([pp[2], 1])); return Mt * lm
        T = frame(cs[:3]) @ np.linalg.inv(frame(S.fixed))
        p, q = x2[:n + 1], x2[n + 1:]
        P2, Q2 = _seed.moebius_poly(p, T, n), _seed.moebius_poly(q, T, n)
        xx = np.concatenate([P2, Q2]); xx = xx / (xx @ S.L)
        Ti = np.linalg.inv(T); cnew = (Ti[0, 0] * cs + Ti[0, 1]) / (Ti[1, 0] * cs + Ti[1, 1])
        u = np.concatenate([xx, cnew[3:]])
        try:
            for _ in range(5):
                F, J, _ = S.FJ(u[None], B0[None]); u = u - np.linalg.solve(J[0], F[0])
        except np.linalg.LinAlgError: return None
        F, _, _ = S.FJ(u[None], B0[None])
        return u if np.linalg.norm(F) < 1e-9 * (1 + np.abs(u).max()) else None
    def add_images(new):
        cnt = 0
        for u, o in new:
            p, q, cc = S.unpack(u[None]); an = an_of(u)
            cand = []
            for x2, an2 in closure.images(np.concatenate([p[0], q[0]]), an, n, prof):
                u2 = to_u(x2, an2)
                if u2 is not None: cand.append(u2)
            cnt += len(accept(cand, oid=o))
        return cnt
    def save(loop):
        tmp = ckpt + '.tmp'
        pickle.dump({'sols': np.array(sols), 'orbit': orbit, 'reps': reps, 'GRP': GRP, 'REJ': REJ, 'L': L,
                     'fixed': fixed, 'ys': S.ys, 'loop': loop, 'rng': rng.bit_generator.state, 'W': W}, open(tmp, 'wb'))
        os.replace(tmp, ckpt)
    start_loop = 0
    if os.path.exists(ckpt):
        d = pickle.load(open(ckpt, 'rb')); L = d['L']; S = System(n, prof, fixed, L)
        rng.bit_generator.state = d['rng']; start_loop = d['loop'] + 1
        # rebuild bookkeeping from the stored covers (recomputes tuples once)
        Us = d['sols']; p, q, _ = S.unpack(Us)
        for u, t, o in zip(Us, ft.tuples(p, q, TM), d['orbit']):
            cf, au = md.canon(t); TUP.add(cf); W += 1 / au; sols.append(u); orbit.append(o)
        reps[:] = d['reps']; GRP.update(d['GRP']); REJ[:] = d['REJ']
        print(f'resumed from {ckpt}: {len(sols)} covers, {len(reps)} orbits, loop {start_loop}', flush=True)
    else:
        want = set(int(g) for g in a.groups.split(',') if g)
        tries = 0
        while True:
            raw = []
            while not raw: raw = _seed.seq_seed(n, prof, fixed, L, rng, starts=20, verbose=False)
            u_, assign, cc_ = raw[0]; xg = u_[:2 * n + 2]; tries += 1
            an0 = analyse(xg[:n + 1], xg[n + 1:], n, prof, cc_, list(assign)) or analyse_loose(xg[:n + 1], xg[n + 1:], n, prof, cc_, list(assign))
            sd = to_u(xg, an0) if an0 is not None else None
            if sd is not None:
                nw = accept([sd])
                if nw: add_images(nw)
            have = set(GRP.values())
            print(f'seed try {tries}: groups so far {sorted(have)}  covers {len(sols)}  t={time.time()-t0:.1f}s', flush=True)
            if want <= have and sols: break
            if not want and sols: break
        save(-1)
    print(f'target weighted {target}', flush=True)
    tracks = 0
    for loop in range(start_loop, a.loops):
        def rnd():
            Wr = B0.copy(); fin = [0, 2, 3, 4, 5]
            Wr[fin, 0] = B0[fin, 0] + a.scale * (rng.normal(size=5) + 1j * rng.normal(size=5)); return Wr
        B1, B2 = rnd(), rnd()
        idx = np.arange(len(sols)) if a.all else np.array(reps)
        U0 = np.array(sols)[idx]; U = U0.copy(); okall = np.ones(len(U), bool)
        for Wa, Wb in ((B0, B1), (B1, B2), (B2, B0)):
            U, ok, st = track(S, U, Wa, Wb); okall &= ok
        if (~okall).any():
            Uf = U0[~okall]; okf = np.ones(len(Uf), bool)
            for Wa, Wb in ((B0, B1), (B1, B2), (B2, B0)):
                Uf, ok, st = track(S, Uf, Wa, Wb, h0=0.002, hmin=1e-12, dmax=1e-2); okf &= ok
            U[~okall] = Uf; ii = np.nonzero(~okall)[0]; okall[ii[okf]] = True
        tracks += len(U)
        nw = accept(list(U[okall])); new = len(nw) + add_images(nw)
        grp = {}
        for o in range(len(reps)): grp[GRP[o]] = grp.get(GRP[o], 0) + 1
        print(f'loop {loop}: tracked {len(U)} (failed {(~okall).sum()}), new {new}, covers {len(sols)} '
              f'orbits {len(reps)} {grp} weighted {W:.4f}/{target} rej {len(REJ)} t={time.time()-t0:.1f}s', flush=True)
        save(loop)
        if W >= target - 1e-9 or time.time() - t0 > a.maxtime: break
    print(f'done: covers {len(sols)} weighted {W} target {target}; orbits {len(reps)}; tracks {tracks}; '
          f'rejected {len(REJ)}; time {time.time()-t0:.1f}s', flush=True)
    from covers import fingerprint
    covs = []
    for u in sols:
        p, q, cc = S.unpack(u[None]); covs.append((np.concatenate([p[0], q[0]]), fingerprint(an_of(u))[1]))
    pickle.dump({'sols': np.array(sols), 'ys': S.ys, 'REJ': REJ, 'L': L, 'fixed': fixed}, open(f'rej_{tag}.pkl', 'wb'))
    pickle.dump({'n': n, 'prof': prof, 'covers': covs}, open(f'cov_{tag}.pkl', 'wb'))

if __name__ == '__main__': main()
