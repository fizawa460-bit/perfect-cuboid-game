#!/usr/bin/env python3
"""Stage32 D10-LOW-GENUS: exact checks for CONTRACT.md.

What this script ACTUALLY checks (exact integer / rational arithmetic unless stated):
  A. Symmetry: each generator in enumeration/symmetry_generators.json permutes the 140 known curves preserving the
     four types (labels 1-32, 33-44, 45-92, 93-140) and the full 140x140 intersection matrix; it induces an
     integral 64x64 matrix Q (c_i Q = c_{p(i)} for all 140 curves) with Q G Q^T = G and K Q = K. The generated group
     has order 6144.
  B. Inventory and orbit coverage: the records in enumeration/results.jsonl are EXACTLY the generated jobs
     (57 slices; per slice the orbit representatives of the boundary vectors); recomputed independently here:
     the union of the slice-group orbits of the representatives equals the set of all boundary vectors of
     the slice (every boundary vector is a group image of a representative); record fields match job keys; one producer; producer = sha256(producer_info); sources_sha256 equals
     the current source files; cflags fixed; producer_info.binary_sha256 equals enumeration/PROVENANCE.json
     (that this hash is what the committed source compiles to is checked by enumeration/reproduce_binary.sh).
  C. Every EMPTY / CONGRUENCE_EMPTY record recomputed independently (rational nullspace, normal-equation
     particular solution, column-lattice HNF; M = -N^T G N positive definite by exact pivots); all other records
     COMPLETE.
  D. Expansion: the union over representative records of (slice group) x (classes found) equals
     enumeration/classes_d10.json; every listed class satisfies K.x = 10, F1.x = n1, sum Exc.x = e,
     x^2 >= c2min, x.Gamma >= 0 for the 140 curves; the set is closed under each slice group; 256 classes.
  E. Decomposition: for every class, K - x = (sum of three distinct conics) + (nonnegative combination of the
     exceptional curves), and this is the ONLY way to write K - x as (known non-exceptional curves of total
     degree 6) + (nonnegative exceptional combination).
  F. Residuals: residuals/triples.json is regenerated by residuals/make_residuals.py and compared (span ranks of all
     4960 conic triples, the representative map, automorphism checks); residuals/results.txt has, for each of the
     832 representatives and BOTH projections, a RESULT line; whenever the residual has degree 10 the plane model
     has degree 10 (birational projection); the two projections agree; and no representative has an absolutely
     irreducible degree-10 residual of genus <= 1.
NOT checked here: the enumeration itself (enumeration/run_d10.py), the Singular runs (residuals/run_residuals.py),
or the geometric arguments of CONTRACT.md.
usage: PYTHONUTF8=1 python verify_d10_low_genus.py [REPO_ROOT]
"""
import hashlib
import itertools
import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

import numpy as np
from flint import fmpz_mat, fmpq_mat, fmpq

HERE = Path(__file__).resolve().parent
REPO = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else HERE.parents[3]
sys.path.insert(0, str(HERE / "enumeration"))
import slice_lib as L  # noqa: E402
import run_d10 as RD  # noqa: E402
ok = True


def check(cond, msg):
    global ok
    print(("PASS " if cond else "FAIL ") + msg, flush=True)
    ok &= bool(cond)


L.load(REPO)
Gn, Pn, Cn = L.D["Gn"], L.D["Pn"], L.D["Cn"]
I140 = [[int(Pn[i].dot(Cn[j])) for j in range(140)] for i in range(140)]
typ = lambda i: 0 if i < 32 else 1 if i < 44 else 2 if i < 92 else 3
Gq = fmpq_mat([[fmpq(int(v)) for v in r] for r in Gn.tolist()])
kq = Gq.solve(fmpq_mat([[fmpq(int(v))] for v in L.D["deg"]]))
Kv = np.array([int(kq[i, 0].p) for i in range(64)], dtype=object)
assert all(kq[i, 0].q == 1 for i in range(64))

# ---- A ---------------------------------------------------------------------------------------------------------------
gens = json.loads((HERE / "enumeration/symmetry_generators.json").read_text())["generators"]
basis_idx, rk = [], 0
for i in range(140):
    if fmpz_mat([[int(v) for v in Cn[k]] for k in basis_idx + [i]]).rank() > rk:
        basis_idx.append(i); rk += 1
    if rk == 64:
        break
Binv = fmpq_mat([[fmpq(int(v)) for v in Cn[i]] for i in basis_idx]).inv()


def qmat(p):
    Q = Binv * fmpq_mat([[fmpq(int(v)) for v in Cn[p[i]]] for i in basis_idx])
    return Q


goodA = True
for p in gens:
    goodA &= sorted(p) == list(range(140)) and all(typ(p[i]) == typ(i) for i in range(140))
    goodA &= all(I140[p[i]][p[j]] == I140[i][j] for i in range(140) for j in range(140))
    Q = qmat(p)
    goodA &= all(Q[r, c].q == 1 for r in range(64) for c in range(64))
    goodA &= all((fmpq_mat([[fmpq(int(v)) for v in Cn[i]]]) * Q) == fmpq_mat([[fmpq(int(v)) for v in Cn[p[i]]]]) for i in range(140))
    goodA &= (Q * Gq * Q.transpose()) == Gq
    goodA &= (fmpq_mat([[fmpq(int(v)) for v in Kv]]) * Q) == fmpq_mat([[fmpq(int(v)) for v in Kv]])
grp = L.group(gens)
check(goodA and len(grp) == 6144, f"A {len(gens)} generators: type- and intersection-preserving, integral Gram- and K-preserving isometries; group order {len(grp)}")
Qof = {}


def Qn(g_):
    if g_ not in Qof:
        Q = qmat(g_)
        Qof[g_] = np.array([[int(Q[r, c].p) for c in range(64)] for r in range(64)], dtype=object)
    return Qof[g_]


# ---- B ---------------------------------------------------------------------------------------------------------------
recs = [json.loads(l) for l in (HERE / "enumeration/results.jsonl").read_text().splitlines() if l.strip()]
byjob = {r["job"]: r for r in recs}
prov = json.loads((HERE / "enumeration/PROVENANCE.json").read_text())
expected = {}
cover_ok = True
order = L.D["V"] + L.D["H"]
for (n1, e, c2) in RD.inventory():
    use = RD.slice_use(grp, n1)
    pats = L.bvectors(n1, 10 - n1, e)
    reps = L.orbit_reps(pats, use)
    for r, p_ in enumerate(reps):
        expected[f"{n1}|{e}|{c2}|{r}"] = (n1, e, c2, [list(t) for t in p_])
    if not reps:
        expected[f"{n1}|{e}|{c2}|NOB"] = (n1, e, c2, None)
    # independent coverage: the union of the G_slice-orbits of the representatives is exactly the set of all
    # boundary vectors of the slice (so every boundary vector is the image of some representative)
    allk = {tuple(v for _, v in p_) for p_ in pats}
    orb = set()
    for p_ in reps:
        for g_ in use:
            orb.add(tuple(L.act_b(g_, p_)[l] for l in order))
    if orb != allk:
        cover_ok = False
info0 = recs[0].get("producer_info", {})
provB = (len({r.get("producer") for r in recs}) == 1 and recs[0]["producer"] == RD.producer_of(info0)
         and info0.get("sources_sha256") == RD.sources_sha256() and info0.get("cflags") == RD.CFLAGS
         and info0.get("binary_sha256") == prov.get("binary_sha256") and info0.get("compiler") == prov.get("compiler")
         and all(r.get("producer_info") == info0 for r in recs))
fieldsB = all(byjob[k]["n1"] == v[0] and byjob[k]["e"] == v[1] and byjob[k]["c2min"] == v[2] and byjob[k]["fixes"] == v[3]
              for k, v in expected.items() if k in byjob)
check(len(recs) == len(byjob) and set(byjob) == set(expected) and cover_ok and provB and fieldsB,
      f"B {len(recs)} records = exactly the {len(expected)} generated jobs; every boundary vector covered by a representative; "
      "fields match keys; single producer bound to current sources, fixed CFLAGS and the PROVENANCE binary hash")

# ---- C ---------------------------------------------------------------------------------------------------------------
rowsK = [[int(v) for v in L.D["deg"]], [int(v) for v in L.D["F1row"]], [int(v) for v in L.D["exc"]]]


def indep(n1, e, c2, fixes):
    rows = rowsK + [[int(v) for v in Pn[lab - 1]] for lab, _ in (fixes or [])]
    t = [10, n1, e] + [v for _, v in (fixes or [])]
    A = fmpz_mat(rows)
    Hh = fmpz_mat(A.transpose().tolist()).hnf()
    res = list(t)
    for i in range(Hh.nrows()):
        row = [int(Hh[i, j]) for j in range(Hh.ncols())]
        pv = next((j for j, x in enumerate(row) if x), None)
        if pv is None:
            continue
        if res[pv] % row[pv]:
            break
        q = res[pv] // row[pv]
        res = [a_ - q * b_ for a_, b_ in zip(res, row)]
    solvable = all(x == 0 for x in res)
    Aq = fmpq_mat(A.tolist())
    rk_ = A.rank()
    # rational particular solution via least-norm on an independent row subset
    sel, cur = [], 0
    for i in range(len(rows)):
        if fmpz_mat([rows[k] for k in sel + [i]]).rank() > cur:
            sel.append(i); cur += 1
    As = fmpq_mat([rows[i] for i in sel]); ts = fmpq_mat([[fmpq(t[i])] for i in sel])
    consistent = (Aq * (As.transpose() * (As * As.transpose()).inv() * ts)) == fmpq_mat([[fmpq(x)] for x in t])
    if not consistent:
        return False, None, True
    xp = As.transpose() * (As * As.transpose()).inv() * ts
    X, nul = A.nullspace()
    N = fmpq_mat([[X[i, j] for j in range(nul)] for i in range(64)])
    M = -(N.transpose() * Gq * N)
    nn = M.nrows(); Mw = [[M[i, j] for j in range(nn)] for i in range(nn)]; pd = True
    for k in range(nn):
        if not Mw[k][k] > 0:
            pd = False; break
        for i in range(k + 1, nn):
            f_ = Mw[i][k] / Mw[k][k]
            if f_ != 0:
                for j in range(k + 1, nn):
                    Mw[i][j] -= f_ * Mw[k][j]
    bvec = N.transpose() * Gq * xp
    R = (xp.transpose() * Gq * xp)[0, 0] + (bvec.transpose() * M.solve(bvec))[0, 0] - c2
    return solvable and consistent, R, pd


goodC, nbad = True, []
for k, r in byjob.items():
    st = r["status"].split()[0]
    if st == "NO_BVECTOR":
        goodC &= not L.bvectors(r["n1"], 10 - r["n1"], r["e"]); continue
    if st in ("CONGRUENCE_EMPTY", "EMPTY"):
        sol_, R, pd = indep(r["n1"], r["e"], r["c2min"], r["fixes"])
        if st == "CONGRUENCE_EMPTY" and sol_:
            nbad.append(k)
        if st == "EMPTY" and not (sol_ and pd and R < 0):
            nbad.append(k)
    elif st != "COMPLETE":
        nbad.append(k)
check(goodC and not nbad, f"C every EMPTY / CONGRUENCE_EMPTY claim recomputed independently; all other records COMPLETE" + (f"; bad {nbad[:5]}" if nbad else ""))

# ---- D ---------------------------------------------------------------------------------------------------------------
final = {tuple(x) for x in json.loads((HERE / "enumeration/classes_d10.json").read_text())["classes"]}
expanded = set()
for r in recs:
    if not r["classes"]:
        continue
    use = RD.slice_use(grp, r["n1"])
    for x in r["classes"]:
        xv = np.array(x, dtype=object)
        for g_ in use:
            expanded.add(tuple(int(v) for v in xv.dot(Qn(g_))))
goodD = expanded == final
pat = Counter()
for x in final:
    xv = np.array(x, dtype=object); pr = Pn.dot(xv); c2 = int(xv.dot(Gn).dot(xv))
    n1 = int(L.D["F1row"].dot(xv)); e = int(sum(pr[92:]))
    goodD &= int(L.D["deg"].dot(xv)) == 10 and (pr >= 0).all() and c2 >= (-12 if e >= 2 * max(n1, 10 - n1) + 4 else -10)
    pat[(n1, e, c2)] += 1
check(goodD and len(final) == 256, f"D expansion of the representative classes = classes_d10.json; all {len(final)} classes valid; (n1, e, C^2) counts {dict(pat)}")

# ---- E ---------------------------------------------------------------------------------------------------------------
degs = [int(L.D["deg"].dot(Cn[i])) for i in range(140)]
nonexc = [i for i in range(92) if degs[i] > 0]
combos = [cb for r_ in range(1, 4) for cb in itertools.combinations_with_replacement(nonexc, r_) if sum(degs[i] for i in cb) == 6]
Ex = np.array([[int(v) for v in Cn[k]] for k in range(92, 140)], dtype=np.int64)          # 48 x 64
Gi = np.array(Gn.tolist(), dtype=np.int64)
GE = Gi.dot(Ex.T)                                                                      # 64 x 48
CB = np.array([sum((np.array([int(v) for v in Cn[i]], dtype=np.int64) for i in cb), np.zeros(64, dtype=np.int64)) for cb in combos])
Kn = np.array([int(v) for v in Kv], dtype=np.int64)
goodE = True
for x in final:
    T = Kn - np.array(x, dtype=np.int64) - CB                                          # (#combos) x 64
    A2 = -T.dot(GE)                                                                    # = 2 * exceptional coefficients
    okrow = (A2 % 2 == 0).all(axis=1) & (A2 >= 0).all(axis=1)
    okrow &= ~((T - (A2 // 2).dot(Ex)) != 0).any(axis=1)
    hits = [combos[i] for i in np.nonzero(okrow)[0]]
    goodE &= len(hits) == 1 and len(hits[0]) == 3 and len(set(hits[0])) == 3 and all(i < 32 for i in hits[0])
check(goodE, f"E for all {len(final)} classes: K - x = three distinct conics + nonnegative exceptional combination, uniquely (among {len(combos)} degree-6 combinations)")

# ---- F ---------------------------------------------------------------------------------------------------------------
import tempfile, shutil  # noqa: E402
tmp = Path(tempfile.mkdtemp())
subprocess.run([sys.executable, str(HERE / "residuals/make_residuals.py"), str(tmp)], check=True, capture_output=True)
same_tri = (tmp / "triples.json").read_bytes() == (HERE / "residuals/triples.json").read_bytes()
same_sing = all((tmp / "sing" / p.name).read_bytes() == p.read_bytes() for p in (HERE / "residuals/sing").glob("*.sing")) and \
    len(list((tmp / "sing").glob("*.sing"))) == len(list((HERE / "residuals/sing").glob("*.sing")))
shutil.rmtree(tmp)
tri = json.loads((HERE / "residuals/triples.json").read_text())
reps = sorted({tuple(v) for v in tri["map"].values()})
res = {}
for line in (HERE / "residuals/results.txt").read_text().splitlines():
    m = re.search(r"RESULT (\d+) (\d+) (\d+) proj (\d) resdeg (\d+) planegens (\d+) planedeg (\d+) absfactors (\d+) genus (-?\d+)", line)
    if m:
        v = tuple(int(x) for x in m.groups())
        res[(v[0], v[1], v[2], v[3])] = v[4:]
goodF = same_tri and same_sing and tri["info"]["triples_by_span_rank"] == {"5": 96, "6": 1728, "7": 3136}
summary = Counter()
for r_ in reps:
    a1, a2 = res.get(r_ + (1,)), res.get(r_ + (2,))
    if a1 is None or a2 is None:
        goodF = False; continue
    rd, ng, pd_, na, gg = a1
    goodF &= (rd, na, gg) == (a2[0], a2[3], a2[4])            # projections agree on degree, factors, genus
    if rd == 10:
        goodF &= pd_ == 10 and ng == 1 and a2[2] == 10
    goodF &= not (rd == 10 and na == 1 and 0 <= gg <= 1)
    summary[(rd, na, gg)] += 1
check(goodF, f"F triples/scripts reproduced; ranks {tri['info']['triples_by_span_rank']}; {len(reps)} representatives, both projections agree; "
      f"(residual degree, absolute factors, genus) counts {dict(summary)}; no irreducible degree-10 residual of genus <= 1")

print("ALL PASS" if ok else "SOME CHECKS FAILED")
sys.exit(0 if ok else 1)
