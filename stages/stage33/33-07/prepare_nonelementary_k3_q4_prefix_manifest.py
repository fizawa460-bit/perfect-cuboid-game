"""Prepare the complete exact-prefix universe for the k=3 full-Q[4] leaf.

The predecessor certificate has already reduced the k=3 non-elementary branch
of H ~= (Z/4)^3 + (Z/2)^3 to 572,522,496 integral-cc/ct-stable H, compressed
without canonical pruning into 189 exact (P,W) skeleton orbits and affine lift
fibres.  This preparatory leaf reconstructs every one of those affine fibres
from the source equations.

For K=H^perp, R={x in A0:4x in H}, and theta:R->Hom(H,Q/Z), the endpoint
condition |(K/H)[4]|=2^24 is equivalent to

    log2 |im(theta)| = 4-t,

where t=rank(P_X).  Maximal Q[2] implies 2R<=K, hence im(theta) is elementary.
A section-independent subgroup generated by A0[4] and roots of 2(W cap Y)
has exact F2 rank 3 on every one of the 189 skeleton orbits.  Therefore all
t=2 fibres are rejected immediately because their target image rank is 2.

For t=1 the target rank is 3.  We select, for each skeleton orbit, one explicit
theta functional/annihilator pair which is outside the fixed rank-3 subgroup
at the canonical section and at every affine basis direction.  The selection
is NOT used as a completeness argument: the follow-up shards exhaust all
2^d sections in disjoint six-bit prefixes and check the chosen obstruction on
every section, with an exact full-rank fallback if it ever vanishes.

No fast/canonical traversal is used or trusted here.
"""
