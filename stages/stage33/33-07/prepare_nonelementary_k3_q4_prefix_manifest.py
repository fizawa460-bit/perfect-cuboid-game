PREFIX_BITS = 6
NVAR = 24
X_MASK = (1 << 10) - 1

# Re-execute the complete predecessor exactly once.  Its own firewall rebuilds
# all 2,628 skeletons, all 189 orbits, all retained cc/ct action choices, and
# the Burnside counts without heuristic representative traversal.
pre_ns = runpy.run_path(str(HERE / 'certify_nonelementary_k3_integral_cc_ct_orbits.py'))
