EXPECTED_SRC_SHA256 = "30f2a4653619419a42d5513be26c8acf7505e042e4cbef279abd3476c34d1cfa"


def canonical_sha256(obj):
    return hashlib.sha256(
        json.dumps(obj, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()


def rref2(rows, ncols):
    a = [[int(x) & 1 for x in row] for row in rows]
    pivots = []
    r = 0
    for c in range(ncols):
        p = next((i for i in range(r, len(a)) if a[i][c]), None)
        if p is None:
            continue
        a[r], a[p] = a[p], a[r]
        for i in range(len(a)):
            if i != r and a[i][c]:
                a[i] = [x ^ y for x, y in zip(a[i], a[r])]
        pivots.append(c)
        r += 1
        if r == len(a):
            break
    return a, pivots


def rank2(rows, ncols):
    return len(rref2(rows, ncols)[1])


def inv2(matrix):
    n = len(matrix)
    a = [
        [int(x) & 1 for x in matrix[i]] + [int(i == j) for j in range(n)]
        for i in range(n)
    ]
    for c in range(n):
        p = next((i for i in range(c, n) if a[i][c]), None)
        if p is None:
            raise SystemExit("basis-change matrix is singular")
        a[c], a[p] = a[p], a[c]
        for i in range(n):
            if i != c and a[i][c]:
                a[i] = [x ^ y for x, y in zip(a[i], a[c])]
    return [row[n:] for row in a]


def bits_from_hex_le(value, nbits):
    z = int(value, 16)
    return [(z >> i) & 1 for i in range(nbits)]


src = json.loads(SRC.read_text(encoding="utf-8"))
body = dict(src)
claimed = body.pop("canonical_sha256")
if claimed != EXPECTED_SRC_SHA256 or canonical_sha256(body) != EXPECTED_SRC_SHA256:
    raise SystemExit("raw-order4 Bockstein compact source lock moved")

q = src["quotient_to_raw_bockstein"]
if q != {
    "double_obstruction_rank_f2": 9,
    "quotient_A2_dimension_f2": 26,
    "raw_order2_kernel_dimension_f2": 17,
    "raw_order4_quotient_dimension_f2": 9,
}:
    raise SystemExit(f"unexpected quotient-to-raw dimensions: {q}")
records = src["nine_source_records"]
if len(records) != 9:
    raise SystemExit("expected nine order-four source records")
if any(int(r["raw_residue_exact_order"]) != 4 for r in records):
    raise SystemExit("a Bockstein source lost exact raw order four")
if any(int(r["parent_order"]) != 2 for r in records):
    raise SystemExit("a raw-order4 direction is no longer quotient order two")
if any(not r["complex_conjugation_defect_equals_double_obstruction"] for r in records):
    raise SystemExit("complex-conjugation defect source lock moved")

obstructions = [
    bits_from_hex_le(r["double_obstruction_U44_f2_hex_le"], 44)
    for r in records
]
if rank2(obstructions, 44) != 9:
    raise SystemExit("nine Bockstein images are not independent")

# Use the nine obstruction images as the first nine vectors of a new U44 basis
# and greedily extend with the old standard U44 basis.
new_u44_basis = [row[:] for row in obstructions]
complement_old_indices = []
rank_now = 9
for j in range(44):
    e = [0] * 44
    e[j] = 1
    new_rank = rank2(new_u44_basis + [e], 44)
    if new_rank > rank_now:
        new_u44_basis.append(e)
        complement_old_indices.append(j + 1)
        rank_now = new_rank
if len(new_u44_basis) != 44 or len(complement_old_indices) != 35 or rank_now != 44:
    raise SystemExit("failed to extend Bockstein image to a U44 basis")

inverse = inv2(new_u44_basis)
# Row-vector convention: new_u44_basis rows are new basis vectors in old
# coordinates.  Hash both directions rather than bloating the retained file.
forward_hash = canonical_sha256(new_u44_basis)
inverse_hash = canonical_sha256(inverse)

source_names = [r["source_basis_name"] for r in records]
if source_names != [f"A2_{i:02d}" for i in range(15, 24)]:
    raise SystemExit(f"unexpected order-four source block: {source_names}")

# Exact invariant-factor bookkeeping.  Modulo U44 the 26 chosen lifts are an
# F2 basis.  Seventeen have square zero in the raw extension; nine have
# independent nonzero doubles, now the first nine U44 basis vectors.
