order2_factors = (44 - 9) + 17
if order2_factors != 52:
    raise SystemExit("extension invariant-factor bookkeeping regression")
order_log2 = 2 * order4_factors + order2_factors
if order_log2 != 44 + 26:
    raise SystemExit("extension order disagrees with kernel times quotient")

normal_form_pairs = []
for i, r in enumerate(records, 1):
    normal_form_pairs.append({
        "order4_source": r["source_basis_name"],
        "new_u44_double_basis_name": f"U44_BOCK_{i:02d}",
        "double_relation": f"2*{r['source_basis_name']}=U44_BOCK_{i:02d}",
        "complex_conjugation_relation": (
            f"cc({r['source_basis_name']})={r['source_basis_name']}+U44_BOCK_{i:02d}"
        ),
        "complex_conjugation_on_Z4_factor": "inversion",
        "raw_order4_function_package_sha256": r["full_order4_function_package_sha256"],
    })

