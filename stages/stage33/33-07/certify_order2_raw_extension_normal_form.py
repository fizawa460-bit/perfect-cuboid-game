#!/usr/bin/env python3
"""Put the #1419 9-dimensional quotient-to-raw Bockstein extension in normal form.

Input: the compact certificate proving 17 raw-order2 and 9 exact raw-order4
first-residue directions, with nine independent U44 doubles.

Because the 26 quotient A[2] sources form a basis modulo U44, and the nine
nonzero doubles are independent in U44, the subgroup generated by U44 and the
26 chosen raw lifts has exact invariant factors

    (Z/4)^9 direct_sum (Z/2)^52.

This leaf constructs an explicit U44 basis whose first nine vectors are the
nine Bockstein images, so each order-four source q_i satisfies 2 q_i = u'_i.
It also records the already-certified complex-conjugation identity
cc(q_i)-q_i = u'_i, hence cc acts by inversion on each of the nine Z/4 factors.

No global Gersten lift or arithmetic localization cocycle is claimed.
"""

import hashlib
import json
