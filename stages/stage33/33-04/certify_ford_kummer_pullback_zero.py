# Choose Ls as the projective line at infinity.  Every affine line factor is
# represented in the function field by Li/Ls, and under the endpoint map each
# such ratio is the square (root_i/c)^2.
infinity = "Ls"
affine = [k for k in lines if k != infinity]
pullback_ratios = {
    k: f"({roots[k]}/{roots[infinity]})^2" for k in affine
}

# Ford's audited line-arrangement Br[2] presentation is generated by degree-two
# symbols in the affine line factors, modulo concurrence/incidence relations.
# Since every affine factor pulls back to a square, every ambient pair-symbol
# already vanishes in the endpoint function field.  Hence any quotient of their
# span, including the certified 9-dimensional Ford group, has zero pullback.
pairs = []
for i, a in enumerate(affine):
    for b in affine[i+1:]:
        pairs.append({
            "symbol": f"({a}/{infinity}, {b}/{infinity})_2",
            "first_pullback": pullback_ratios[a],
            "second_pullback": pullback_ratios[b],
            "pullback_zero_reason": "both entries are squares",
        })

assert len(affine) == 6
assert len(pairs) == 15
assert set(roots) == set(lines)

