# Seven audited branch lines on P^2.
lines = {
    "Lx": "x",
    "Ly": "y",
    "Lz": "z",
    "Lxy": "x+y",
    "Lxz": "x+z",
    "Lyz": "y+z",
    "Ls": "x+y+z",
}

# Exact endpoint Kummer/sign-cover square roots.
